# Base dictionary mapping
dictionary = {}

# 1. Load curriculum data first
with open('english_data.json', 'r', encoding='utf-8') as f:
    curriculum = json.load(f)

for day in curriculum:
    for w in day.get('words', []):
        key = w['word'].strip().lower()
        dictionary[key] = {
            'w': w['word'],
            'p': w.get('phonetic', ''),
            'pos': w.get('pos', ''),
            'd': w.get('def', '')
        }
        # Also map individual words in multi-word terms
        parts = key.split()
        if len(parts) > 1:
            for part in parts:
                if len(part) >= 3 and part not in dictionary:
                    dictionary[part] = {
                        'w': part.capitalize(),
                        'p': '',
                        'pos': '词汇',
                        'd': f'与【{w["word"]}】相关的核心词汇'
                    }

